// Refreshes assets/js/products.js - the products the blog's ads show - from the public
// collection feeds on fangviper.com (read-only; only products the store has published).
// Run from the repo root:  node --use-system-ca tools/sync-products.js
const fs = require("fs");
const path = require("path");

const STORE = "https://fangviper.com";
// One entry per store collection the ads draw from. A product in several collections keeps the first.
const COLLECTIONS = [
  { handle: "tees-polos", cat: "tee", noun: "Tee", kicker: "Wear the reminder" },
  { handle: "stay-awake", cat: "mug", noun: "Mug", kicker: "Morning ritual" },
  { handle: "hydration", cat: "bottle", noun: "Bottle", kicker: "Stay cold. Stay sharp" },
  { handle: "pack-go", cat: "bag", noun: "Gym Bag", kicker: "Carry the work" },
  { handle: "manifest", cat: "journal", noun: "Journal", kicker: "Log the work" },
];
const OUT = path.join(__dirname, "..", "assets", "js", "products.js");

const sleep = ms => new Promise(r => setTimeout(r, ms));
async function getJson(url) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0 (fangviper-blog product sync)" } });
    if (res.ok) return res.json();
    if (res.status !== 429 || attempt === 4) throw new Error(`${url} -> HTTP ${res.status}`);
    await sleep(3000 * attempt);
  }
}

// "nobody is coming" -> "Nobody Is Coming"; short all-caps words (ROI) stay, long ones (TEXT) soften
const titleCase = s => s.trim().split(/\s+/).map(w => {
  if (w.length > 3 && w === w.toUpperCase()) w = w.toLowerCase();
  return w.charAt(0).toUpperCase() + w.slice(1);
}).join(" ");

function adName(title, noun) {
  const name = titleCase(title);
  const last = noun.split(" ").pop().toLowerCase();
  return name.toLowerCase().endsWith(last) ? name : `${name} ${noun}`;
}

(async () => {
  const seen = new Set(), products = [];
  for (const c of COLLECTIONS) {
    let count = 0;
    for (let page = 1; ; page++) {
      const { products: batch } = await getJson(`${STORE}/collections/${c.handle}/products.json?limit=250&page=${page}`);
      for (const p of batch) {
        const image = p.images && p.images[0];
        const prices = p.variants.filter(v => v.available).map(v => Number(v.price));
        if (seen.has(p.handle) || !image || !prices.length) continue;
        seen.add(p.handle);
        products.push({
          id: p.handle,
          name: adName(p.title, c.noun),
          price: "$" + Math.min(...prices).toFixed(2),
          cat: c.cat,
          kicker: c.kicker,
          img: image.src,
        });
        count++;
      }
      if (batch.length < 250) break;
      await sleep(800);
    }
    console.log(`${c.handle}: ${count} products`);
    await sleep(800);
  }
  if (!products.length) throw new Error("No products found - products.js left unchanged");

  const day = new Date().toISOString().slice(0, 10);
  const body = products.map(p => JSON.stringify(p)).join(",\n");
  fs.writeFileSync(OUT,
    `// Generated by tools/sync-products.js from the fangviper.com collections on ${day}. Do not edit by hand:\n` +
    `// re-run \`node --use-system-ca tools/sync-products.js\` after store changes.\n` +
    `window.FV_PRODUCTS = [\n${body}\n];\n`);
  console.log(`Wrote ${products.length} products to ${path.relative(process.cwd(), OUT)}`);
})().catch(err => { console.error(err.message); process.exit(1); });
